// Deterministic randomness: a seed and a key (campaign, day, segment) always give the same numbers.
// ---------------------------------------------------------------------------

/** FNV-1a, 32 bits: a stable hash of a short string, to seed one stream per campaign-day. */
function fnv1a(s: string): number {
  let h = 0x811c9dc5;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 0x01000193);
  }
  return h >>> 0;
}

/** mulberry32: a small, fast PRNG with a 32-bit state; plenty for sample data. */
function mulberry32(state: number): () => number {
  let a = state >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** A stream of numbers in [0, 1) for `key` under `seed`. */
export const demoRng = (seed: number, key: string): (() => number) => mulberry32(fnv1a(`${Math.trunc(seed) >>> 0}:${key}`));

/** A seed for a new demo (or a reset): any positive 31-bit integer. */
export const isDemoSeed = (v: unknown): v is number => typeof v === "number" && Number.isInteger(v) && v > 0 && v <= 0x7fffffff;

/** A fresh seed, from the clock and a little entropy; never 0. */
export function newDemoSeed(now = Date.now()): number {
  const seed = (fnv1a(`${now}:${Math.random()}`) & 0x7fffffff) || 1;
  return seed;
}

