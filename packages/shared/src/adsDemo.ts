/** Whole numbers that add up to `total`, in proportion to `weights` (largest remainder; a zero total gives zeros). */
export function apportion(total: number, weights: number[]): number[] {
  const sum = weights.reduce((a, b) => a + b, 0);
  if (total <= 0 || sum <= 0) return weights.map(() => 0);
  const raw = weights.map((w) => (total * w) / sum);
  const floors = raw.map(Math.floor);
  let left = total - floors.reduce((a, b) => a + b, 0);
  const order = raw.map((v, i) => ({ i, frac: v - floors[i]! })).sort((a, b) => b.frac - a.frac || a.i - b.i);
  for (const { i } of order) {
    if (left <= 0) break;
    floors[i]!++;
    left--;
  }
  return floors;
}

/** Amounts to the cent that add up to `total`, in proportion to `weights` (the residue goes to the biggest). */
export function apportionMoney(total: number, weights: number[]): number[] {
  const cents = apportion(Math.round(total * 100), weights);
  return cents.map((c) => c / 100);
}

const sums = (rows: ReadonlyArray<Pick<AdDayRow, "spend" | "impressions" | "clicks" | "conversions" | "conversionValue">>) =>
  rows.reduce(
    (a, r) => {
      a.spend += r.spend;
      a.impressions += r.impressions;
      a.clicks += r.clicks;
      a.conversions += r.conversions;
      a.conversionValue += r.conversionValue;
      return a;
    },
    { spend: 0, impressions: 0, clicks: 0, conversions: 0, conversionValue: 0 },
  );

/** Google's report metrics from plain sums (the report works in millionths of the currency). */
export const demoReportMetrics = (t: { spend: number; impressions: number; clicks: number; conversions: number; conversionValue: number }): GoogleReportMetrics =>
  googleReportMetrics({ costMicros: Math.round(t.spend * 1_000_000), impressions: t.impressions, clicks: t.clicks, conversions: t.conversions, conversionsValue: t.conversionValue });

/**
 * The rows' totals split by `kind`. Shares are the split's, jittered a little by the seed so no two
 * demos look alike; each segment's rates (click-through, conversion, cost per click, value) differ from
 * the whole in a fixed way, and every column is then scaled to add up exactly to the totals, whole
 * numbers for counts and cents for money. Biggest spend first.
 */
export function demoBreakdown(ctx: Pick<DemoContext, "seed" | "currency">, kind: DemoBreakdown, rows: ReadonlyArray<AdDayRow>): DemoBreakdownRow[] {
  const segments = segmentsOf(kind, ctx.currency);
  const t = sums(rows);
  const r = demoRng(ctx.seed, `breakdown:${kind}`);
  const jitter = segments.map(() => 0.85 + 0.3 * r());
  const impW = segments.map((s, i) => s.weight * jitter[i]!);
  const impressions = apportion(t.impressions, impW);
  const clicks = apportion(t.clicks, segments.map((s, i) => impressions[i]! * s.ctr));
  const conversions = apportion(t.conversions, segments.map((s, i) => clicks[i]! * s.cvr));
  const spend = apportionMoney(t.spend, segments.map((s, i) => clicks[i]! * s.cpc));
  const value = apportionMoney(t.conversionValue, segments.map((s, i) => conversions[i]! * s.aov));
  return segments
    .map((s, i) => ({
      id: s.id,
      name: s.name,
      share: t.spend > 0 ? spend[i]! / t.spend : null,
      ...demoReportMetrics({ spend: spend[i]!, impressions: impressions[i]!, clicks: Math.min(clicks[i]!, impressions[i]!), conversions: Math.min(conversions[i]!, clicks[i]!), conversionValue: value[i]! }),
    }))
    .sort((a, b) => b.spend - a.spend || b.impressions - a.impressions || a.name.localeCompare(b.name));
}

