/** What generating a demo's figures needs: its seed, its currency, and its first day (the day it was connected, in its own time zone). */
export interface DemoContext {
  seed: number;
  currency: string;
  /** YYYY-MM-DD. The campaigns' starts and the 90-day trends are set relative to it, so they never move once the demo exists. */
  epoch: string;
}

const r2 = (n: number) => Math.round(n * 100) / 100;

/** An amount in US dollars as the account's currency, rounded to that currency's minor unit. */
export function demoMoney(usd: number, currency: string): number {
  const units = minorUnitsPerUnit(currency);
  return Math.round(usd * demoCurrencyRate(currency) * units) / units;
}

/** Days since 2020-01-01, for slow waves that don't restart with each campaign. */
const dayIndex = (day: string) => daysBetweenInclusive("2020-01-01", day) - 1;
/** 0 (Sunday) to 6 (Saturday). */
const weekdayOf = (day: string) => new Date(`${day}T00:00:00Z`).getUTCDay();

/** The campaign's first day and, when paused, its last. */
export function demoCampaignDays(ctx: Pick<DemoContext, "epoch">, c: DemoCampaign): { start: string; end: string | null } {
  return { start: addDays(ctx.epoch, -c.startedDaysBefore), end: c.pausedDaysBefore === null ? null : addDays(ctx.epoch, -c.pausedDaysBefore) };
}

/**
 * One campaign's figures for one day, as Google would report them (AdDayRow): null on a day before
 * the campaign started or after it was paused. Impressions follow the campaign's base, the weekday, a
 * week-long ramp after the start, the campaign's trend over the 90 days up to the epoch and a slow
 * wave; clicks never exceed impressions, conversions never exceed clicks, and spend stays under twice
 * the daily budget (as Google's overdelivery does). Every figure is consistent with the others: the
 * rates the page works out (CTR, CPC, conversion rate, ROAS) are true of the row.
 */
/** Where `day` sits in the 90 days up to the epoch: 0 at their start, 1 at the epoch, beyond 1 after it. */
const trendAt = (ctx: DemoContext, day: string) => 1 - (daysBetweenInclusive(day, ctx.epoch) - 1) / (DEMO_HISTORY_DAYS - 1);

export function demoCampaignDay(ctx: DemoContext, c: DemoCampaign, day: string): AdDayRow | null {
  const { start, end } = demoCampaignDays(ctx, c);
  if (day < start || (end !== null && day > end)) return null;
  const r = demoRng(ctx.seed, `${c.id}:${day}`);
  const noise = (lo: number, hi: number) => lo + (hi - lo) * r();
  const p = c.profile;
  const age = daysBetweenInclusive(start, day) - 1;
  const ramp = Math.min(1, (age + 1) / 7);
  const wd = weekdayOf(day);
  const weekend = wd === 0 || wd === 6 ? p.weekend : 1;
  const pos = trendAt(ctx, day);
  const trend = Math.max(0.3, 1 + p.trend * pos);
  const phase = demoRng(ctx.seed, `${c.id}:phase`)() * Math.PI * 2;
  const wave = 1 + 0.08 * Math.sin((2 * Math.PI * dayIndex(day)) / 28 + phase);
  const impressions = Math.max(0, Math.round(p.impressions * weekend * ramp * trend * wave * noise(0.82, 1.22)));
  const clicks = Math.min(impressions, Math.round(impressions * p.ctr * noise(0.85, 1.15)));
  const cpcUsd = p.cpcUsd * Math.max(0.2, 1 + p.cpcTrend * pos) * noise(0.9, 1.12);
  const spendUsd = Math.min(clicks * cpcUsd, c.dailyBudgetUsd * 1.6);
  const cvr = p.cvr * Math.max(0.2, 1 + p.cvrTrend * pos) * noise(0.7, 1.3);
  const conversions = Math.min(clicks, Math.round(clicks * cvr));
  const leads = Math.round(conversions * p.leadShare);
  const purchases = conversions - leads;
  const purchaseValue = demoMoney(purchases * p.aovUsd * noise(0.8, 1.2), ctx.currency);
  return {
    provider: "google",
    accountId: DEMO_ACCOUNT_ID,
    campaignId: c.id,
    campaignName: c.name,
    day,
    spend: demoMoney(spendUsd, ctx.currency),
    impressions,
    clicks,
    // Google's clicks are clicks on the ad: the comparable figure, as fromGoogleAdsRow stores it.
    linkClicks: clicks,
    conversions,
    // Leads carry no value; the conversion value is the purchases'.
    conversionValue: purchaseValue,
    purchases,
    purchaseValue,
    leads,
    // As Google Ads' campaign.status would say it, so the demo's campaigns filter like a real account's.
    campaignStatus: c.status,
  };
}

/** Every campaign's figures for the days of [since, until] (both included), as a sync stores them. */
export function demoCampaignRows(ctx: DemoContext, since: string, until: string): AdDayRow[] {
  if (!isDay(since) || !isDay(until) || since > until) return [];
  const rows: AdDayRow[] = [];
  for (const day of eachDay(since, until)) {
    for (const c of DEMO_CAMPAIGNS) {
      const row = demoCampaignDay(ctx, c, day);
      if (row) rows.push(row);
    }
  }
  return rows;
}

/**
 * A demo campaign's delivery as Google's campaign.primary_status would rate it on `today` (not for any dates):
 * paused when it is; limited by budget when an ordinary day's clicks then would cost more than its daily
 * budget (its days' spend is held down by the budget, demoCampaignDay); otherwise eligible. An ordinary day
 * is demoCampaignDay's on `today` without its noise, weekday, ramp or wave: its base with its trends as of
 * that day, so the rating follows what its days spend then. Every demo budget is a daily one.
 */
export function demoPrimaryStatus(ctx: DemoContext, c: DemoCampaign, today: string): { primaryStatus: string; primaryStatusReasons: string[] } {
  if (c.status === "PAUSED") return { primaryStatus: "PAUSED", primaryStatusReasons: ["CAMPAIGN_PAUSED"] };
  const p = c.profile;
  const pos = trendAt(ctx, today);
  const clicks = p.impressions * Math.max(0.3, 1 + p.trend * pos) * p.ctr;
  const cost = clicks * p.cpcUsd * Math.max(0.2, 1 + p.cpcTrend * pos);
  return cost > c.dailyBudgetUsd ? { primaryStatus: "LIMITED", primaryStatusReasons: ["BUDGET_CONSTRAINED"] } : { primaryStatus: "ELIGIBLE", primaryStatusReasons: [] };
}

