const NA = "N/A";
const ratio = (a: number, b: number) => (b > 0 ? a / b : null);
/** A figure some days don't have yet (older days being read again from the platform). */
const known = (v: number | null, show: (n: number) => string) => (v === null ? BEING_READ : show(v));

