/** The series for one measure, one line per platform, in platform order. */
function perPlatform(pick: (p: Provider) => Array<number | null> | null): LineSeries[] {
  return (["meta", "google", "adsense"] as Provider[])
    .map((p) => ({ p, values: pick(p) }))
    .filter((x): x is { p: Provider; values: Array<number | null> } => x.values !== null)
    .map(({ p, values }) => ({ key: p, label: PLATFORM[p].name, color: PLATFORM[p].color, values }));
}

function Trends({ ov, fetching }: { ov: Overview; fetching: boolean }) {
  const ads = ov.modules.ads;
  const sense = ov.modules.adsense;
  const days = (ads?.series ?? sense?.series ?? []).map((d) => d.day);
  const byP = (p: "meta" | "google") => ads?.seriesByProvider.find((s) => s.provider === p)?.series ?? null;
  const sameMoney = !ads || !sense || ads.currency === sense.currency;
  const spendSeries = perPlatform((p) => (p === "adsense" ? null : (byP(p)?.map((d) => d.spend) ?? null))).map((s) => ({ ...s, label: `${s.label} spend` }));
  const earnSeries: LineSeries[] = sense ? [{ key: "adsense", label: "AdSense estimated earnings", color: PLATFORM.adsense.color, values: sense.series.map((d) => d.earnings) }] : [];
  const impressions = perPlatform((p) => (p === "adsense" ? (sense?.series.map((d) => d.impressions) ?? null) : (byP(p)?.map((d) => d.impressions) ?? null)));
  // Link clicks for the ad platforms; AdSense's clicks are clicks on the ads on your site.
  const clicks = perPlatform((p) => (p === "adsense" ? (sense?.series.map((d) => d.clicks) ?? null) : (byP(p)?.map((d) => d.linkClicks) ?? null)));
  const unread = (s: LineSeries[]) => s.every((x) => x.values.every((v) => v === null));
  const quiet = (s: LineSeries[]) => s.every((x) => x.values.every((v) => v === null || v === 0));

  const plot = (series: LineSeries[], format: (v: number) => string, fmtAxis: (v: number, step: number) => string, label: string, integer = false) =>
    fetching && quiet(series) ? (
      <div className="skeleton h-40" aria-hidden="true" />
    ) : unread(series) ? (
      <p className="rounded-lg border border-dashed border-border px-3 py-6 text-center text-sm text-muted">No figures for these dates yet: see above for why.</p>
    ) : quiet(series) && series.every((x) => x.values.every((v) => v !== null)) ? (
      <p className="rounded-lg border border-dashed border-border px-3 py-6 text-center text-sm text-muted">No ad activity in these dates.</p>
    ) : (
      <LineChart days={days} series={series} format={format} fmtAxis={fmtAxis} label={label} today={ov.today} integer={integer} />
    );

  const moneyCur = ads?.currency ?? sense?.currency ?? "USD";
  const money = (cur: string) => (v: number) => fmtMoney(v, cur);
  // Whole amounts are short; gridlines less than a unit apart (a quiet AdSense day) need the cents.
  const axis = (cur: string) => (v: number, step: number) => (step < 1 ? fmtMoney(v, cur) : fmtMoneyCompact(v, cur));
  const count = (v: number) => new Intl.NumberFormat(undefined, { notation: "compact" }).format(v);
  const span = fmtRange(ov.range.from, ov.range.to);
  const gaps = [...spendSeries, ...earnSeries].some((s) => s.values.some((v) => v === null)) ? " Days a platform has no figures for yet are left blank, not drawn as 0." : "";

  return (
    <div className="mt-4 space-y-4">
      {sameMoney ? (
        <ChartCard
          title={ads && sense ? "Ad spend and estimated ad earnings per day" : ads ? "Ad spend per day" : "Estimated ad earnings per day"}
          sub={`${span}, in ${moneyCur}.${ads && sense ? " Spend is what you paid for ads; estimated earnings are what AdSense expects to pay you, not money paid out yet." : ""}${gaps}`}
          testid="ads-money-chart"
        >
          {plot([...spendSeries, ...earnSeries], money(moneyCur), axis(moneyCur), `Ad spend and earnings per day, ${span}`)}
        </ChartCard>
      ) : (
        <div className="grid gap-4 lg:grid-cols-2">
          <ChartCard title="Ad spend per day" sub={`${span}, in ${ads!.currency}.${gaps}`} testid="ads-money-chart">
            {plot(spendSeries, money(ads!.currency), axis(ads!.currency), `Ad spend per day, ${span}`)}
          </ChartCard>
          <ChartCard title="Estimated ad earnings per day" sub={`${span}, in ${sense!.currency}.`} testid="ads-earnings-chart">
            {plot(earnSeries, money(sense!.currency), axis(sense!.currency), `Ad earnings per day, ${span}`)}
          </ChartCard>
        </div>
      )}
      <div className="grid gap-4 lg:grid-cols-2">
        <ChartCard title="Impressions per day" sub="Times ads were shown, by platform (AdSense: ad requests that delivered an ad)." testid="ads-impressions-chart">
          {plot(impressions, fmtNum, count, `Impressions per day by platform, ${span}`, true)}
        </ChartCard>
        <ChartCard title="Link clicks per day" sub="Clicks on the ads' links, by platform (AdSense: clicks on the ads on your site)." testid="ads-clicks-chart">
          {plot(clicks, fmtNum, count, `Link clicks per day by platform, ${span}`, true)}
        </ChartCard>
      </div>
    </div>
  );
}

/** Platforms side by side, on the measures that mean the same thing on each. */
function Comparison({ ov }: { ov: Overview }) {
  const ads = ov.modules.ads;
  const sense = ov.modules.adsense;
  type Row = { p: Provider; money: string; kind: "spent" | "earned" | null; through: string | null; impressions: string; clicks: string; ctr: string; perClick: string; per1000: string; purchases: string; roas: string; demo?: boolean };
  const rows: Row[] = [];
  const blank = (p: Provider): Row => ({ p, money: UNAVAILABLE, kind: null, through: null, impressions: "—", clicks: "—", ctr: "—", perClick: "—", per1000: "—", purchases: "—", roas: "—" });
  for (const b of ads?.byProvider ?? []) {
    const cur = ads!.currency;
    const { totals: c, through } = shownFigures(b);
    if (!c) {
      rows.push({ ...blank(b.provider), demo: !!b.demo });
      continue;
    }
    rows.push({
      p: b.provider,
      demo: !!b.demo,
      money: fmtMoney(c.spend, cur),
      kind: "spent",
      through,
      impressions: fmtNum(c.impressions),
      clicks: known(c.linkClicks, fmtNum),
      ctr: c.linkClicks === null ? BEING_READ : c.ctr === null ? NA : fmtPct(c.ctr),
      perClick: c.linkClicks === null ? BEING_READ : c.cpc === null ? NA : fmtMoney(c.cpc, cur),
      per1000: c.cpm === null ? NA : fmtMoney(c.cpm, cur),
      purchases: known(c.purchases, fmtNum),
      roas: c.purchases === null ? BEING_READ : fmtTimes(c.roas, NA),
    });
  }
  if (sense) {
    const { totals: c, through } = shownFigures(sense);
    if (!c) rows.push(blank("adsense"));
    else {
      const rpm = ratio(c.earnings * 1000, c.impressions);
      rows.push({
        p: "adsense",
        money: fmtMoney(c.earnings, sense.currency),
        kind: "earned",
        through,
        impressions: fmtNum(c.impressions),
        clicks: fmtNum(c.clicks),
        ctr: c.ctr === null ? NA : fmtPct(c.ctr),
        perClick: c.perClick === null ? NA : fmtMoney(c.perClick, sense.currency),
        per1000: rpm === null ? NA : fmtMoney(rpm, sense.currency),
        purchases: NA,
        roas: NA,
      });
    }
  }
  if (rows.length < 2) return null;
  return (
    <div className="card mt-4 min-w-0" data-testid="ads-comparison">
      <h3 className="font-semibold">By platform</h3>
      <p className="text-xs text-muted">
        Each platform&apos;s own numbers for these dates. Spent is what you paid for ads; earned is AdSense&apos;s estimate of what it will pay you, not money paid out yet.
      </p>
      <div className="-mx-1 mt-3 overflow-x-auto">
        <table className="w-full min-w-[46rem] text-sm">
          <thead className="text-left text-xs text-muted">
            <tr>
              <th className="px-1 pb-2 font-normal">Platform</th>
              <th className="px-1 pb-2 text-right font-normal">Money</th>
              <th className="px-1 pb-2 text-right font-normal">Impressions</th>
              <th className="px-1 pb-2 text-right font-normal">Link clicks</th>
              <th className="px-1 pb-2 text-right font-normal">Click-through rate</th>
              <th className="px-1 pb-2 text-right font-normal">Per click</th>
              <th className="px-1 pb-2 text-right font-normal">Per 1,000 impressions</th>
              <th className="px-1 pb-2 text-right font-normal">Purchases (platform&apos;s count)</th>
              <th className="px-1 pb-2 text-right font-normal">ROAS (platform&apos;s own)</th>
            </tr>
          </thead>
          <tbody>
            {rows.map((r) => {
              const P = PLATFORM[r.p];
              return (
                <tr key={r.p} className="border-t border-border">
                  <td className="px-1 py-2">
                    <span className="inline-flex items-center gap-2 font-medium">
                      <span aria-hidden className="inline-block h-2.5 w-2.5 rounded-sm" style={{ background: P.color }} />
                      <P.Icon size={16} />
                      {P.name}
                      {r.demo && <DemoChip small />}
                    </span>
                    {r.through && <span className="block text-xs text-muted">{upToWords(r.through)}</span>}
                  </td>
                  <td className="px-1 py-2 text-right tabular-nums">
                    {r.money} {r.kind && <span className="text-xs text-muted">{r.kind}</span>}
                  </td>
                  <td className="px-1 py-2 text-right tabular-nums">{r.impressions}</td>
                  <td className="px-1 py-2 text-right tabular-nums">{r.clicks}</td>
                  <td className="px-1 py-2 text-right tabular-nums">{r.ctr}</td>
                  <td className="px-1 py-2 text-right tabular-nums">
                    {r.perClick} {r.kind && <span className="text-xs text-muted">{r.kind === "spent" ? "cost" : "earned"}</span>}
                  </td>
                  <td className="px-1 py-2 text-right tabular-nums">
                    {r.per1000} {r.kind && <span className="text-xs text-muted">{r.kind === "spent" ? "cost" : "earned"}</span>}
                  </td>
                  <td className="px-1 py-2 text-right tabular-nums">{r.purchases}</td>
                  <td className="px-1 py-2 text-right tabular-nums">{r.roas}</td>
                </tr>
              );
            })}
          </tbody>
        </table>
      </div>
      <p className="mt-2 text-xs text-muted">
        Purchases and ROAS are each platform&apos;s own count and can overlap; they aren&apos;t your Shopify orders, which are above. Google Ads&apos; other conversions
        (leads, sign-ups, calls) are on its card, never counted as purchases. AdSense doesn&apos;t report purchases.
      </p>
    </div>
  );
}

/** The platforms this server can connect, in order. */
const offered = (ov: Overview) => (["google", "meta", "adsense"] as Provider[]).filter((p) => ov.modules.ad_configured?.[p]);

/** A quiet way to add the platforms that aren't connected yet, without getting in the way. */
function ConnectMore({ ov }: { ov: Overview }) {
  const n = ov.modules.ad_connections;
  // A platform whose sign-in is connected and waiting for its ad accounts isn't offered again.
  const missing = offered(ov).filter((p) => !n || (n[p] === 0 && !n.waiting?.includes(p)));
  if (!missing.length) return null;
  return (
    <p className="mt-3 flex flex-wrap items-center gap-2 text-xs text-muted" data-testid="ads-connect-more">
      Connect more:
      {missing.map((p) => (
        <Link key={p} href="/settings/ads" className="rounded-lg border border-border px-2 py-0.5 hover:border-accent hover:text-text">
          {PLATFORM[p].name}
        </Link>
      ))}
    </p>
  );
}

/**
 * `embedded`: on the Advertising area's overview, whose page has its title and its headline tiles
 * already: no heading and no total spend card.
 */
export function AdvertisingSection({ ov, manage, embedded = false }: { ov: Overview; manage: boolean; embedded?: boolean }) {
  const ads = ov.modules.ads;
  const sense = ov.modules.adsense;
  if (!ads && !sense) {
    const n = ov.modules.ad_connections;
    const hiddenOnly = !!n && n.meta + n.google + n.adsense > 0 && n.hidden > 0;
    // Never offer a way in that can't work: with no platform set up on this server, say nothing.
    if (!manage || (!hiddenOnly && offered(ov).length === 0)) return null;
    return <Onboarding hiddenOnly={hiddenOnly} offer={offered(ov)} />;
  }
  const accounts: AdAccount[] = [...(ads?.accounts ?? []), ...(sense?.accounts ?? [])];
  const fetching = accounts.some((a) => a.status === "active" && !a.lastSyncedAt);
  const left = accounts.filter((a) => !a.counted);
  return (
    <section aria-labelledby={embedded ? undefined : "ads-h"} aria-label={embedded ? "Advertising by platform" : undefined} data-testid="advertising">
      {!embedded && <SectionHeading manage={manage} />}
      <AdStatusNotes accounts={accounts} manage={manage} />
      <div className="grid gap-4 md:grid-cols-2 xl:grid-cols-3">
        {ads && ads.byProvider.length >= 2 && !embedded && <TotalSpendCard a={ads} ov={ov} />}
        {ads?.byProvider.map((p) => <SpendCard key={p.provider} a={ads} p={p} ov={ov} />)}
        {sense && <EarningsCard a={sense} ov={ov} />}
      </div>
      <Trends ov={ov} fetching={fetching} />
      <Comparison ov={ov} />
      {left.length > 0 && (
        <p className="mt-2 text-xs text-muted">
          Left out of these figures: {left.map((a) => `${a.name ?? a.accountId} (${a.currency ?? "currency not known yet"})`).join(", ")}, because{" "}
          {left.length === 1 ? "it's" : "they're"} in another currency. Amounts in different currencies are never added together.
        </p>
      )}
      {ads && <Definitions items={AD_DEFINITIONS} title="What the ad figures mean" />}
      {sense && <Definitions items={ADSENSE_DEFINITIONS} title="What the AdSense figures mean" />}
      {manage && <ConnectMore ov={ov} />}
      <p className="mt-1 text-xs text-muted">{plural(accounts.length, "account")} connected · updated about every hour, the last 30 days again daily.</p>
    </section>
  );
}
