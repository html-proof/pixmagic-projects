/**
 * One platform's (or all spend's) card: its headline figure with the period before and the change,
 * the platform it comes from and how fresh it is, and one line saying what it is.
 */
function SummaryCard({
  title,
  icon,
  explain,
  source,
  fig,
  today,
  href,
  children,
  note,
  testid,
  demo = false,
}: {
  title: string;
  icon?: ReactNode;
  explain: string;
  source: string;
  /** Simulated figures (the Google Ads demo). */
  demo?: boolean;
  /** How fresh the figures are: when the least recently updated account synced, and the last day they all have. */
  fig: Pick<AdFigures<unknown>, "updatedAt" | "coverage">;
  today: string;
  /** Its page in the Advertising area. */
  href: string;
  children: ReactNode;
  note?: string | null;
  testid: string;
}) {
  const { updatedAt } = fig;
  const through = fig.coverage.through;
  return (
    <div className="card flex min-w-0 flex-col" data-testid={testid}>
      <div className="flex flex-wrap items-start justify-between gap-2">
        <h3 className="flex items-center gap-2 font-semibold">
          {icon}
          {title}
          {demo && <DemoChip />}
        </h3>
        <Link href={href} className="text-xs text-accent underline-offset-2 hover:underline" data-testid={`${testid}-details`}>
          See details
        </Link>
      </div>
      <p className="mt-0.5 text-xs text-muted">{explain}</p>
      <div className="mt-3 flex-1">{children}</div>
      {note && <p className="mt-3 text-xs text-muted">{note}</p>}
      <p className="mt-3 text-xs text-muted" data-testid={`${testid}-source`}>
        Source: {source} · {updatedAt ? `updated ${fmtRelative(updatedAt)}` : "not read yet"}
        {through && through < today ? ` · figures up to ${fmtDay(through, { year: false })}` : ""}
      </p>
    </div>
  );
}

/**
 * The card's main figure: its value (or "Unavailable" with why), the change, and what was compared.
 * `through`: the value is the dates so far, up to that day (the days after it aren't over yet).
 */
function Headline<T>({
  label,
  fig,
  value,
  through,
  change,
  accounts,
  ov,
  show,
}: {
  label: string;
  fig: AdFigures<T>;
  value: string | null;
  through: string | null;
  change: ReactNode;
  accounts: AdAccount[];
  ov: Overview;
  show: (t: T) => string;
}) {
  return (
    <div>
      <p className="text-xs text-muted">{label}</p>
      <p className="mt-0.5 text-2xl font-semibold tabular-nums">{value ?? UNAVAILABLE}</p>
      {value === null ? (
        <p className="mt-1 text-xs text-muted">
          <UnavailableNote fig={fig} accounts={accounts} range={ov.range} show={show} />
        </p>
      ) : (
        <>
          {through && (
            <p className="mt-1 text-xs text-muted">
              <SoFarNote through={through} accounts={accounts} range={ov.range} />
            </p>
          )}
          <p className="mt-1">{change}</p>
          {fig.compared && (
            <p className="mt-1 text-xs text-muted">
              <ComparedLine fig={fig} show={show} />
            </p>
          )}
        </>
      )}
    </div>
  );
}

function Facts({ items }: { items: Array<[string, string]> }) {
  return (
    <dl className="mt-3 grid grid-cols-2 gap-x-3 gap-y-2">
      {items.map(([label, value]) => (
        <div key={label} className="min-w-0">
          <dt className="text-xs text-muted">{label}</dt>
          <dd className="truncate text-sm font-medium tabular-nums">{value}</dd>
        </div>
      ))}
    </dl>
  );
}

/** Why a change isn't there: "No earlier data" in full when that's the reason. */
const historyNote = (fig: Pick<AdFigures<unknown>, "notCompared" | "historyFrom">, source: "ads" | "adsense") => (fig.notCompared === "no_history" ? noEarlierData(fig.historyFrom, source) : null);

function SpendCard({ a, p, ov }: { a: AdsModule; p: AdsProviderFigures; ov: Overview }) {
  const P = PLATFORM[p.provider];
  const money = (n: number) => fmtMoney(n, a.currency);
  const accounts = a.accounts.filter((acc) => acc.counted && acc.provider === p.provider);
  const { totals: c, through } = shownFigures(p);
  const facts: Array<[string, string]> = c
    ? [
        ["Link clicks", known(c.linkClicks, fmtNum)],
        ["Purchases (platform's count)", known(c.purchases, fmtNum)],
        [`${P.short}-reported ROAS`, c.purchases === null ? BEING_READ : fmtTimes(c.roas, NA)],
        ...(p.provider === "google" ? [["Conversions (all conversion actions)", fmtNum(c.conversions)] as [string, string]] : []),
        // The store's own sales per unit of ad spend (MER), when this is the only platform spending: every sale, not the platform's claim.
        ...(a.byProvider.length === 1 && a.sales ? [[`Your sales per ${fmtMoneyWhole(1, a.currency)} of ads (MER)`, fmtTimes(a.sales.salesPerSpend, NA)] as [string, string]] : []),
      ]
    : [];
  return (
    <SummaryCard
      title={P.name}
      icon={<P.Icon size={18} />}
      explain={P.explain}
      source={P.name}
      fig={p}
      today={ov.today}
      href={`/advertising/${p.provider}`}
      note={[timeZoneNote(accounts), historyNote(p, "ads"), p.demo ? "Simulated figures from the Google Ads demo: not set against your store's sales. The Google Ads analytics page sets them against a simulated store." : null].filter(Boolean).join(" ") || null}
      testid={`ads-card-${p.provider}`}
      demo={!!p.demo}
    >
      <Headline label="Ad spend" fig={p} value={c ? money(c.spend) : null} through={through} change={<ChangeNote fig={p} value={p.deltas.spend} ov={ov} neutral />} accounts={accounts} ov={ov} show={(t) => money(t.spend)} />
      {facts.length > 0 && <Facts items={facts} />}
    </SummaryCard>
  );
}

