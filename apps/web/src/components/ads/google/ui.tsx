"use client";
import type { ReactNode } from "react";
import type { AdsMetrics } from "@app/shared/adsAnalytics";
import type { DemoBreakdownRow } from "@app/shared/adsDemo";
import { fmtMoney, fmtNum, fmtPct } from "@/lib/api";
import { fmtTimes } from "@/components/dashboard/format";

// ---------------------------------------------------------------------------
// What the Google Ads analytics page's sections share: the DEMO DATA badge, the way a figure is
// written ("—" where its denominator was zero, never a division error), and a table of one split
// (devices, countries, age groups, audience segments) with its share of the spend drawn as a bar.
// ---------------------------------------------------------------------------

export const NA = "—";

/** Simulated figures: said on the page's title and on every section that shows them. */
export function DemoDataBadge({ className = "" }: { className?: string }) {
  return (
    <span
      className={`inline-flex items-center gap-1 rounded-full border border-warn/40 bg-warn/10 px-2 py-0.5 text-xs font-semibold text-warn ${className}`}
      data-testid="demo-data-badge"
      title="Simulated figures generated by bizinsights for the Google Ads demo. Not verified by Google."
    >
      DEMO DATA
    </span>
  );
}

/** The figures as the page writes them, in the account's currency. */
export function figureWriters(currency: string) {
  const money = (n: number | null | undefined) => (n === null || n === undefined ? NA : fmtMoney(n, currency));
  const num = (n: number | null | undefined) => (n === null || n === undefined ? NA : fmtNum(n));
  const pct = (n: number | null | undefined) => (n === null || n === undefined ? NA : fmtPct(n));
  const times = (n: number | null | undefined) => (n === null || n === undefined ? NA : fmtTimes(n));
  return { money, num, pct, times };
}

export type Writers = ReturnType<typeof figureWriters>;

/** The columns every metrics table shares, in order, with how each is written. */
export const METRIC_COLUMNS: Array<{ key: keyof AdsMetrics; label: string; kind: "money" | "num" | "pct" | "times" }> = [
  { key: "spend", label: "Spend", kind: "money" },
  { key: "impressions", label: "Impressions", kind: "num" },
  { key: "clicks", label: "Clicks", kind: "num" },
  { key: "ctr", label: "CTR", kind: "pct" },
  { key: "cpc", label: "Avg. CPC", kind: "money" },
  { key: "conversions", label: "Conversions", kind: "num" },
  { key: "conversionRate", label: "Conv. rate", kind: "pct" },
  { key: "costPerConversion", label: "Cost / conv.", kind: "money" },
  { key: "conversionValue", label: "Conv. value", kind: "money" },
  { key: "roas", label: "ROAS", kind: "times" },
];

export const writeMetric = (w: Writers, kind: (typeof METRIC_COLUMNS)[number]["kind"], v: number | null) => (kind === "money" ? w.money(v) : kind === "num" ? w.num(v) : kind === "pct" ? w.pct(v) : w.times(v));

/** One split's rows: name, its share of the spend as a bar, and the figures. */
export function SplitTable({ rows, w, what, testid, empty = "Nothing in these dates." }: { rows: DemoBreakdownRow[]; w: Writers; what: string; testid: string; empty?: string }) {
  if (!rows.length) return <p className="rounded-lg border border-dashed border-border px-3 py-6 text-center text-sm text-muted">{empty}</p>;
  const max = Math.max(...rows.map((r) => r.share ?? 0), 0);
  return (
    <div className="-mx-1 overflow-x-auto">
      <table className="w-full min-w-[40rem] text-sm" data-testid={testid}>
        <thead className="text-left text-xs text-muted">
          <tr>
            <th className="px-1 pb-2 font-normal">{what}</th>
            <th className="px-1 pb-2 font-normal">Share of spend</th>
            <th className="px-1 pb-2 text-right font-normal">Impressions</th>
            <th className="px-1 pb-2 text-right font-normal">Clicks</th>
            <th className="px-1 pb-2 text-right font-normal">CTR</th>
            <th className="px-1 pb-2 text-right font-normal">Spend</th>
            <th className="px-1 pb-2 text-right font-normal">Conversions</th>
            <th className="px-1 pb-2 text-right font-normal">Conv. value</th>
            <th className="px-1 pb-2 text-right font-normal">ROAS</th>
          </tr>
        </thead>
        <tbody>
          {rows.map((r) => (
            <tr key={r.id} className="border-t border-border">
              <td className="px-1 py-2 font-medium">{r.name}</td>
              <td className="px-1 py-2">
                <span className="flex items-center gap-2">
                  <span className="h-2 w-28 overflow-hidden rounded-full bg-border/60" aria-hidden>
                    <span className="block h-full rounded-full bg-[var(--viz-cat-2)]" style={{ width: `${max > 0 ? ((r.share ?? 0) / max) * 100 : 0}%` }} />
                  </span>
                  <span className="tabular-nums text-xs text-muted">{w.pct(r.share)}</span>
                </span>
              </td>
              <td className="px-1 py-2 text-right tabular-nums">{w.num(r.impressions)}</td>
              <td className="px-1 py-2 text-right tabular-nums">{w.num(r.clicks)}</td>
              <td className="px-1 py-2 text-right tabular-nums">{w.pct(r.ctr)}</td>
              <td className="px-1 py-2 text-right tabular-nums">{w.money(r.spend)}</td>
              <td className="px-1 py-2 text-right tabular-nums">{w.num(r.conversions)}</td>
              <td className="px-1 py-2 text-right tabular-nums">{w.money(r.conversionValue)}</td>
              <td className="px-1 py-2 text-right tabular-nums">{w.times(r.roas)}</td>
            </tr>
          ))}
        </tbody>
      </table>
    </div>
  );
}

/** A section's card: a title, one line on what it shows, and the DEMO DATA badge when the figures are simulated. */
export function Section({ id, title, help, demo, aside, children }: { id: string; title: string; help?: ReactNode; demo: boolean; aside?: ReactNode; children: ReactNode }) {
  return (
    <section id={id} className="card min-w-0 animate-rise scroll-mt-28" aria-labelledby={`${id}-h`} data-testid={`ga-${id}`}>
      <div className="flex flex-wrap items-start justify-between gap-x-4 gap-y-1">
        <div className="min-w-0">
          <h2 id={`${id}-h`} className="flex items-center gap-2 font-semibold">
            {title}
            {demo && <DemoDataBadge />}
          </h2>
          {help && <p className="mt-0.5 text-xs text-muted">{help}</p>}
        </div>
        {aside && <div className="text-sm">{aside}</div>}
      </div>
      <div className="mt-4">{children}</div>
    </section>
  );
}

/** Quiet text where a chart has nothing to draw: an empty range never breaks a chart. */
export function Quiet({ children }: { children: ReactNode }) {
  return <p className="rounded-lg border border-dashed border-border px-3 py-6 text-center text-sm text-muted">{children}</p>;
}
