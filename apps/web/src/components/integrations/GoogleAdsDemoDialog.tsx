"use client";
import Link from "next/link";
import { useEffect, useId, useRef, useState, type ReactNode } from "react";
import { DEMO_BADGE, DEMO_DISCLAIMER, DEMO_PERMISSIONS, demoAccountFacts, type DemoAccountFacts } from "@app/shared/adsDemo";
import { overlay } from "@/components/AppUi";
import { GoogleIcon } from "@/components/BrandIcons";
import { Facts } from "@/components/integrations/IntegrationCard";
import { actionError } from "@/lib/api";

// ---------------------------------------------------------------------------
// "Try demo" on the Google Ads card: bizinsights' own connection flow for a simulated Google Ads
// account (docs/ads-demo.md), in five screens. It opens no Google page, asks for no Google account or
// password and grants nothing at Google: the account it connects is generated by bizinsights, and
// every screen says so. Screen 4 makes the real request to the backend and waits for its answer; what
// screen 5 shows is what the server wrote, never a timer's guess.
// ---------------------------------------------------------------------------

/** What POST .../ads/google/demo/connect answers (apps/api/src/routes/adsGoogleDemo.ts). */
export interface DemoConnected {
  success: boolean;
  connection_status: string;
  message: string;
  disclaimer: string;
  demo: DemoAccountFacts & { connectionId: string; seed: number; status: string; permissions: readonly string[]; badge: string; disclaimer: string };
}

type Screen = 1 | 2 | 3 | 4 | 5;

const TITLES: Record<Screen, string> = {
  1: "Google Ads Demo Connection",
  2: "Select Demo Account",
  3: "Demo Data Access",
  4: "Connecting Demo Account…",
  5: "Demo Account Connected",
};

export function GoogleAdsDemoDialog({
  open,
  store,
  onClose,
  onConnect,
  onDisconnect,
}: {
  open: boolean;
  /** The store the demo is connected to: the demo account adopts its currency and time zone. */
  store: { currency: string; timezone: string } | null;
  onClose: () => void;
  /** Screen 4's request: connects the demo on the server and resolves with what it wrote (throws when it couldn't). */
  onConnect: () => Promise<DemoConnected>;
  /** "Disconnect demo" on the last screen. */
  onDisconnect: () => Promise<void>;
}) {
  const id = useId();
  const ref = useRef<HTMLDivElement>(null);
  const [screen, setScreen] = useState<Screen>(1);
  const [error, setError] = useState<string | null>(null);
  const [done, setDone] = useState<DemoConnected | null>(null);
  const [busy, setBusy] = useState(false);
  const facts = demoAccountFacts(store ?? {});

  // Each opening starts at the first screen; the dialog takes the keyboard and gives it back on close.
  useEffect(() => {
    if (!open) return;
    setScreen(1);
    setError(null);
    setDone(null);
    const prev = document.activeElement as HTMLElement | null;
    ref.current?.querySelector<HTMLElement>("button[data-primary]")?.focus();
    return () => prev?.focus();
  }, [open]);

  const close = () => {
    if (!busy) onClose();
  };

  useEffect(() => {
    if (!open) return;
    const onKey = (e: KeyboardEvent) => {
      if (e.key === "Escape") close();
    };
    document.addEventListener("keydown", onKey);
    return () => document.removeEventListener("keydown", onKey);
    // `close` reads the latest `busy` through the closure each time the effect runs.
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [open, busy]);

  // Screen 4: the real request, once.
  useEffect(() => {
    if (!open || screen !== 4) return;
    let live = true;
    setBusy(true);
    setError(null);
    onConnect()
      .then((r) => {
        if (!live) return;
        setDone(r);
        setScreen(5);
      })
      .catch((e: unknown) => {
        if (!live) return;
        setError(actionError(e, "connect the demo account"));
        setScreen(3);
      })
      .finally(() => live && setBusy(false));
    return () => {
      live = false;
    };
    // The request belongs to the screen, not to the callback's identity.
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [open, screen]);

  useEffect(() => {
    if (open && screen !== 4) ref.current?.querySelector<HTMLElement>("button[data-primary], a[data-primary]")?.focus();
  }, [open, screen]);

  if (!open) return null;

  const disconnect = async () => {
    setBusy(true);
    setError(null);
    try {
      await onDisconnect();
      onClose();
    } catch (e) {
      setError(actionError(e, "disconnect the demo"));
    } finally {
      setBusy(false);
    }
  };

  const body: ReactNode =
    screen === 1 ? (
      <>
        <p>You are connecting a simulated advertising account for development and testing.</p>
        <p>No Google account authentication or real advertising data will be used. bizinsights generates the account and its figures itself; nothing is sent to or read from Google.</p>
      </>
    ) : screen === 2 ? (
      <>
        <Facts
          rows={[
            ["Account name", facts.name],
            ["Customer ID", facts.accountId],
            ["Currency", facts.currency],
            ["Time zone", facts.timezone],
            ["Country", facts.country],
            ["Account type", facts.accountType],
            ["Connection", "Simulated"],
          ]}
        />
        <p className="text-xs">The demo account adopts your store&apos;s currency and time zone, so its figures can sit next to your sales.</p>
      </>
    ) : screen === 3 ? (
      <>
        <p>The demo connection may read these simulated capabilities:</p>
        <ul className="list-disc space-y-0.5 pl-5" data-testid="demo-permissions">
          {DEMO_PERMISSIONS.map((p) => (
            <li key={p}>{p}</li>
          ))}
        </ul>
        <p className="text-xs">These are fictional application permissions, not Google OAuth scopes. No Google permission is requested or granted.</p>
        {error && (
          <p className="text-danger" role="alert">
            {error}
          </p>
        )}
      </>
    ) : screen === 4 ? (
      <div className="flex items-center gap-3 py-2" role="status" aria-live="polite">
        <span aria-hidden className="inline-block h-5 w-5 animate-spin rounded-full border-2 border-current border-t-transparent text-accent" />
        <span>Connecting demo account… writing the simulated connection and queueing its first 90 days of figures.</span>
      </div>
    ) : (
      <>
        <p>Your Google Ads demo account has been connected successfully to this application&apos;s simulation environment.</p>
        <p className="flex flex-wrap items-center gap-2">
          <span className="rounded-full border border-border px-2 py-0.5 text-xs" data-testid="demo-status">
            Demo Connected
          </span>
          <span className="rounded-full border border-warn/40 bg-warn/10 px-2 py-0.5 text-xs font-medium text-warn" data-testid="demo-verification">
            {done?.demo.badge ?? DEMO_BADGE}
          </span>
        </p>
        <Facts
          rows={[
            ["Account", `${done?.demo.name ?? facts.name} · ${done?.demo.accountId ?? facts.accountId}`],
            ["Status", done?.connection_status === "demo_syncing" ? "Demo connected · fetching its first 90 days" : "Demo connected"],
            ["Demo seed", String(done?.demo.seed ?? "—")],
          ]}
        />
        <p className="text-xs">{done?.disclaimer ?? DEMO_DISCLAIMER}</p>
        {error && (
          <p className="text-danger" role="alert">
            {error}
          </p>
        )}
      </>
    );

  return overlay(
    <div className="fixed inset-0 z-40 flex items-end justify-center bg-black/40 p-4 sm:items-center" onClick={close}>
      <div ref={ref} role="dialog" aria-modal="true" aria-labelledby={id} className="card animate-sheet w-full max-w-lg" onClick={(e) => e.stopPropagation()} data-testid="google-ads-demo-dialog" data-screen={screen}>
        <div className="flex items-start justify-between gap-3">
          <h2 id={id} className="flex items-center gap-2 text-lg font-semibold">
            <GoogleIcon size={20} />
            {TITLES[screen]}
          </h2>
          <span className="rounded-full border border-warn/40 bg-warn/10 px-2 py-0.5 text-xs font-medium text-warn">DEMO</span>
        </div>
        <p className="mt-1 text-xs text-muted">Step {screen} of 5 · simulated, nothing reaches Google</p>
        <div className="mt-3 space-y-2 text-sm text-muted">{body}</div>
        <div className="mt-5 flex flex-wrap justify-end gap-2">
          {screen < 4 && (
            <button type="button" className="btn-secondary" onClick={close}>
              Cancel
            </button>
          )}
          {screen === 1 && (
            <button type="button" className="btn-primary" data-primary onClick={() => setScreen(2)}>
              Continue with Demo
            </button>
          )}
          {screen === 2 && (
            <button type="button" className="btn-primary" data-primary onClick={() => setScreen(3)}>
              Connect Demo Account
            </button>
          )}
          {screen === 3 && (
            <button type="button" className="btn-primary" data-primary onClick={() => setScreen(4)}>
              Authorize Demo Access
            </button>
          )}
          {screen === 5 && (
            <>
              <button type="button" className="text-sm text-danger underline-offset-2 hover:underline disabled:opacity-60" onClick={() => void disconnect()} disabled={busy} data-testid="demo-dialog-disconnect">
                {busy ? "Disconnecting…" : "Disconnect Demo"}
              </button>
              <button type="button" className="btn-secondary" onClick={close} disabled={busy}>
                Done
              </button>
              <Link className="btn-primary" data-primary href="/ads/google" onClick={close}>
                Open Demo Dashboard
              </Link>
            </>
          )}
        </div>
      </div>
    </div>,
  );
}
